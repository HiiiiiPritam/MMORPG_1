export const isWalkable = (mapId: string, x: number, y: number) => {
  const map = maps[mapId];
  if (!map || x < 0 || x >= map.width || y < 0 || y >= map.height) return false;
  const tile = map.grid[y][x];
  // Collisions: 3, 5, 11, 13 (walls/buildings). 8 (bed), 9 (desk), 17 (tt table), 18 (hoop).
  return ![3, 5, 11, 13, 8, 9, 17, 18].includes(tile);
};

export const getTileInteraction = (mapId: string, x: number, y: number): { type: string, target?: string } | null => {
  const map = maps[mapId];
  if (!map || x < 0 || x >= map.width || y < 0 || y >= map.height) return null;
  const tile = map.grid[y][x];
  if (tile === 2) return { type: 'portal', target: 'djlhc_interior' };
  if (tile === 4) return { type: 'portal', target: 'hostel_interior' };
  
  if (tile === 12) return { type: 'portal', target: 'sports_complex' };
  if (tile === 14) return { type: 'portal', target: 'basketball_court' };
  if (tile === 15) return { type: 'portal', target: 'games_room' };
  if (tile === 16) return { type: 'portal', target: 'arena' };
  
  if (tile === 10) {
     if (mapId === 'djlhc_interior' || mapId === 'hostel_interior' || mapId === 'sports_complex') return { type: 'portal', target: 'main_campus' };
     if (mapId === 'basketball_court' || mapId === 'games_room' || mapId === 'arena') return { type: 'portal', target: 'sports_complex' };
     return { type: 'portal', target: 'main_campus' }; // Fallback
  }

  // Adjacent interactions for beds/desks
  if (tile === 8) return { type: 'interact_bed' };
  if (tile === 9) return { type: 'interact_desk' };
  
  // Single-player sports interactions
  if (tile === 17) return { type: 'interact_tt' };
  if (tile === 18) return { type: 'interact_basketball' };

  return null;
};
